// Aynı maldan birden çok kalemi "2 ipek" gibi tek ifadede toplar.
function tally(goods, d) {
  const n = {};
  for (const g of goods) n[g] = (n[g] || 0) + 1;
  return Object.entries(n).map(([g, k]) => `${k} ${d.goodsLower[g]}`);
}

